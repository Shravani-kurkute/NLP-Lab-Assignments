"""
NLP Laboratory - Assignment 05
Generate the Excel workbook of evaluation metrics and experiment comparisons.

Run after PART_A.py and PART_B.py:
    python3 tools/generate_workbook.py
"""

from __future__ import annotations

import json
import os

import pandas as pd
from openpyxl.styles import Alignment, Font, PatternFill
from openpyxl.utils import get_column_letter

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RESULTS = os.path.join(HERE, "results")
OUT = os.path.join(HERE, "evaluation_results.xlsx")

STUDENT = [
    ("Student Name", "Shravani Balasaheb Kurkute"),
    ("Roll No.", "421129"),
    ("PRN / Registration No.", "22311926"),
    ("Class / Division", "BTechA"),
    ("Academic Year", "2026-2027"),
    ("Faculty Name", "Dr. Kapil N. Vhatkar"),
]

HEADER_FILL = PatternFill("solid", fgColor="1F4E79")
HEADER_FONT = Font(bold=True, color="FFFFFF")


def _autofit(writer, sheet):
    ws = writer.sheets[sheet]
    for col in ws.columns:
        width = max((len(str(c.value)) for c in col if c.value is not None), default=10)
        ws.column_dimensions[get_column_letter(col[0].column)].width = min(width + 3, 60)
    for cell in ws[1]:
        cell.fill = HEADER_FILL
        cell.font = HEADER_FONT
        cell.alignment = Alignment(horizontal="center", vertical="center")


def main() -> None:
    with open(os.path.join(RESULTS, "part_a_metrics.json")) as fh:
        a = json.load(fh)
    with open(os.path.join(RESULTS, "part_b_metrics.json")) as fh:
        b = json.load(fh)

    sheets = {}

    # ---- overview / methodology ----
    overview = pd.DataFrame(STUDENT, columns=["Field", "Value"])
    overview.loc[len(overview)] = ["Assignment", "NLP Laboratory Assignment 05 - Sentiment Analysis & Mini Project"]
    overview.loc[len(overview)] = ["Part A dataset", f"{a['dataset']['file']} ({a['dataset']['source']})"]
    overview.loc[len(overview)] = ["Part A cleaned reviews", a["dataset"]["n_clean"]]
    overview.loc[len(overview)] = ["Part B corpus", f"{b['corpus']['name']} ({b['corpus']['n_docs']} docs)"]
    overview.loc[len(overview)] = ["Generated by", "PART_A.py + PART_B.py + tools/generate_workbook.py"]
    sheets["Overview"] = overview

    # ---- Part A ----
    sheets["A_TestMetrics"] = pd.DataFrame(
        sorted(a["test_metrics"].items()), columns=["Metric", "Value"])
    sheets["A_ModelComparison"] = pd.DataFrame(a["cv_comparison"])
    sheets["A_FullCorpus_CV"] = pd.DataFrame(
        sorted(a["cv_full_data"].items()), columns=["Metric", "Value"])

    cm = a["confusion_matrix"]
    sheets["A_ConfusionMatrix"] = pd.DataFrame(
        cm, index=["Actual_Negative", "Actual_Positive"],
        columns=["Predicted_Negative", "Predicted_Positive"]).reset_index().rename(
        columns={"index": ""})

    if os.path.isfile(os.path.join(RESULTS, "part_a_misclassified.csv")):
        miss = pd.read_csv(os.path.join(RESULTS, "part_a_misclassified.csv"))
        sheets["A_Misclassified"] = miss
    if os.path.isfile(os.path.join(RESULTS, "part_a_demo_predictions.csv")):
        sheets["A_DemoPredictions"] = pd.read_csv(os.path.join(RESULTS, "part_a_demo_predictions.csv"))

    # ---- Part B ----
    sheets["B_Ours_Mean"] = pd.read_csv(os.path.join(RESULTS, "part_b_ours_mean.csv"))
    sheets["B_Ours_Std"] = pd.read_csv(os.path.join(RESULTS, "part_b_ours_std.csv"))
    sheets["B_Published_Pang2002"] = pd.read_csv(os.path.join(RESULTS, "part_b_paper_published.csv"))
    sheets["B_Difference"] = pd.read_csv(os.path.join(RESULTS, "part_b_difference.csv"))
    sheets["B_PerSeedResults"] = pd.read_csv(os.path.join(RESULTS, "part_b_results_full.csv"))
    ablation = pd.DataFrame(sorted(b["ablation"].items()), columns=["Setting", "Accuracy_%"])
    sheets["B_Ablation"] = ablation
    sheets["B_FullCorpus10Fold"] = pd.DataFrame(
        sorted(b["full_corpus_10fold"].items()), columns=["Classifier", "Accuracy_%"])
    sheets["B_HumanBaseline"] = pd.DataFrame(
        [["Our Human-1 baseline", b["human_baseline"]["acc"]],
         ["Our Human-1 ties", b["human_baseline"]["ties"]],
         ["Paper Human-1 baseline", b["human_baseline"]["paper"]["acc"]],
         ["Paper Human-1 ties", b["human_baseline"]["paper"]["ties"]]],
        columns=["Item", "Value"])

    with pd.ExcelWriter(OUT, engine="openpyxl") as writer:
        for name, frame in sheets.items():
            frame.to_excel(writer, sheet_name=name, index=False)
            _autofit(writer, name)

    print(f"Wrote {OUT} with {len(sheets)} sheets: {', '.join(sheets)}")


if __name__ == "__main__":
    main()
